ALTER TABLE jobs
  ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY,
  ADD COLUMN company_user_id integer REFERENCES users(id),
  ADD COLUMN status text NOT NULL DEFAULT 'published' CHECK (status IN ('draft', 'published', 'closed')),
  ADD COLUMN deadline date,
  ADD COLUMN created_at timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN published_at timestamptz;

SELECT setval(pg_get_serial_sequence('jobs', 'id'), coalesce(max(id), 0) + 1, false) FROM jobs;

CREATE INDEX company_jobs_idx ON jobs (company_user_id, created_at DESC) WHERE company_user_id IS NOT NULL;
CREATE INDEX applications_job_idx ON applications (job_id, applied_at DESC);
